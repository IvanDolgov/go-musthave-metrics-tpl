// Package models предоставляет структуры данных для работы с метриками.
// Определяет типы метрик и форматы данных для JSON API и файлового хранения.
package models

// MetricType представляет тип метрики.
// Используется для валидации и маршрутизации операций с метриками.
type MetricType string

const (
	// Gauge представляет метрику типа "gauge".
	// Gauge метрики хранят текущее значение, которое может увеличиваться и уменьшаться.
	// Примеры: использование CPU, свободная память, температура.
	Gauge MetricType = "gauge"

	// Counter представляет метрику типа "counter".
	// Counter метрики монотонно увеличиваются (но могут быть сброшены до нуля).
	// Примеры: количество запросов, ошибок, пользователей.
	Counter MetricType = "counter"
)

// Metrics представляет метрику для JSON API.
// Используется для сериализации/десериализации метрик в HTTP запросах и ответах.
//
// Поля структуры:
//   - ID: уникальное имя метрики (обязательное поле)
//   - MType: тип метрики - "gauge" или "counter" (обязательное поле)
//   - Delta: значение для counter метрик (только для типа "counter")
//   - Value: значение для gauge метрик (только для типа "gauge")
//
// Пример JSON для gauge метрики:
//
//	{
//	  "id": "cpu_usage",
//	  "type": "gauge",
//	  "value": 42.5
//	}
//
// Пример JSON для counter метрики:
//
//	{
//	  "id": "requests",
//	  "type": "counter",
//	  "delta": 100
//	}
type Metrics struct {
	// ID - имя метрики.
	// Должно быть уникальным в пределах типа метрики.
	// Используется для идентификации метрики при обновлении и получении.
	ID string `json:"id"`

	// MType - тип метрики.
	// Принимает значения "gauge" или "counter".
	// Определяет какие поля (Value или Delta) должны быть заполнены.
	MType string `json:"type"`

	// Delta - значение метрики в случае передачи counter.
	// Используется только когда MType == "counter".
	// Указывает на сколько увеличить текущее значение счетчика.
	// Может быть отрицательным для уменьшения значения.
	Delta *int64 `json:"delta,omitempty"`

	// Value - значение метрики в случае передачи gauge.
	// Используется только когда MType == "gauge".
	// Устанавливает абсолютное значение gauge метрики.
	Value *float64 `json:"value,omitempty"`
}

// FileMetric представляет метрику для сохранения в файл.
// Используется при сериализации/десериализации метрик в файловое хранилище.
// Отличается от Metrics отсутствием требования к заполнению только одного поля.
//
// Поля структуры:
//   - ID: имя метрики
//   - Type: тип метрики - "gauge" или "counter"
//   - Value: значение для gauge метрик
//   - Delta: значение для counter метрик
type FileMetric struct {
	// ID - имя метрики.
	// Соответствует полю ID в структуре Metrics.
	ID string `json:"id"`

	// Type - тип метрики.
	// Соответствует полю MType в структуре Metrics.
	Type string `json:"type"`

	// Value - значение для gauge метрик.
	// Соответствует полю Value в структуре Metrics.
	// Используется только когда Type == "gauge".
	Value *float64 `json:"value,omitempty"`

	// Delta - значение для counter метрик.
	// Соответствует полю Delta в структуре Metrics.
	// Используется только когда Type == "counter".
	Delta *int64 `json:"delta,omitempty"`
}
